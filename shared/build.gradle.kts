// The iOS app's MARKETING_VERSION from app_version, as Android's versionName; Config.xcconfig includes it.
// Xcode reads xcconfigs before its Gradle build phase runs, so when the value changes this build still
// uses the old one: the task fails it, and the next build picks the new value up.
val generateVersionXcconfig = tasks.register("generateVersionXcconfig") {
    val version = providers.gradleProperty("app_version")
    val output = rootProject.layout.projectDirectory.file("iosApp/Configuration/Version.xcconfig")
    inputs.property("version", version)
    outputs.file(output)
    doLast {
        val file = output.asFile
        val content =
            "// Generated by :shared:generateVersionXcconfig from app_version in gradle.properties.\n" +
                "MARKETING_VERSION = ${version.get()}\n"
        if (file.exists() && file.readText() == content) return@doLast
        file.writeText(content)
        throw GradleException(
            "Version.xcconfig now sets MARKETING_VERSION = ${version.get()}, which this Xcode build read " +
                "before the change. Build again.",
        )
    }
}

tasks.matching { it.name == "embedAndSignAppleFrameworkForXcode" }.configureEach {
